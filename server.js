require('dotenv').config();
const express = require('express');
const path = require('path');
const cors = require('cors');

const menuRoutes = require('./server/routes/menuRoutes');
const mediaRoutes = require('./server/routes/mediaRoutes');
const adminRoutes = require('./server/routes/adminRoutes');

const app = express();
const PORT = process.env.PORT || 3000;

// Security and middleware
app.use(cors());
app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));

// Request logger for monitoring
app.use((req, res, next) => {
  const start = Date.now();
  res.on('finish', () => {
    const duration = Date.now() - start;
    if (req.originalUrl.startsWith('/api')) {
      console.log(`[${new Date().toISOString()}] ${req.method} ${req.originalUrl} ${res.statusCode} (${duration}ms)`);
    }
  });
  next();
});

// API Routes
app.use('/api', menuRoutes);
app.use('/api', mediaRoutes);
app.use('/api/admin', adminRoutes);

// Serve static assets generated by Vite React build in /public
const publicPath = path.join(__dirname, 'public');
app.use(express.static(publicPath));

// Fallback for Single Page Application (SPA) - redirect all unmatched routes to index.html
app.get('*', (req, res) => {
  const indexPath = path.join(publicPath, 'index.html');
  res.sendFile(indexPath, (err) => {
    if (err) {
      res.status(200).send(`
        <!DOCTYPE html>
        <html lang="en">
          <head>
            <meta charset="UTF-8">
            <title>L'Aura Bistro - Digital Restaurant Menu</title>
            <style>
              body { font-family: system-ui, sans-serif; background: #0f172a; color: #f8fafc; display: flex; align-items: center; justify-content: center; min-height: 100vh; margin: 0; text-align: center; }
              .card { background: #1e293b; padding: 2rem; border-radius: 12px; max-width: 500px; border: 1px solid #334155; }
              h1 { color: #f59e0b; margin-top: 0; }
              code { background: #0f172a; padding: 4px 8px; border-radius: 4px; color: #38bdf8; }
            </style>
          </head>
          <body>
            <div class="card">
              <h1>L'Aura Bistro Backend Active</h1>
              <p>The Express API is running successfully on port ${PORT}.</p>
              <p>To view the full React frontend, run:</p>
              <p><code>npm run build</code></p>
              <p>Test the API at: <a href="/api/health" style="color: #38bdf8;">/api/health</a> or <a href="/api/menu" style="color: #38bdf8;">/api/menu</a></p>
            </div>
          </body>
        </html>
      `);
    }
  });
});

// Global JSON Error Handler (Catches Multer 10MB limits or runtime errors)
app.use((err, req, res, next) => {
  console.error('[Server Error Handler]:', err);
  res.status(err.status || 500).json({
    success: false,
    message: err.message || 'An unexpected error occurred on the server'
  });
});

// Start Server
app.listen(PORT, '0.0.0.0', () => {
  console.log(`=======================================================`);
  console.log(`  Restaurant Menu Server running on port ${PORT}`);
  console.log(`  Health Check : http://localhost:${PORT}/api/health`);
  console.log(`  Menu API     : http://localhost:${PORT}/api/menu`);
  console.log(`  Admin API    : http://localhost:${PORT}/api/admin/status`);
  console.log(`  Static Root  : ${publicPath}`);
  console.log(`=======================================================`);
});
